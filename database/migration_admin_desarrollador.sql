CREATE OR REPLACE FUNCTION public.admin_reporte_ventas(
    p_desde date,
    p_hasta date
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
    resultado jsonb;
BEGIN
    IF NOT public.admin_es_desarrollador() THEN
        RAISE EXCEPTION 'Acceso reservado al desarrollador';
    END IF;

    IF p_desde IS NULL OR p_hasta IS NULL OR p_desde > p_hasta THEN
        RAISE EXCEPTION 'Rango de fechas no válido';
    END IF;

    WITH ventas_filtradas AS (
        SELECT v.*
        FROM public.ventas v
        WHERE COALESCE(v.fecha, v.creado_en) >= p_desde::timestamptz
          AND COALESCE(v.fecha, v.creado_en) < (p_hasta + 1)::timestamptz
    ),
    resumen AS (
        SELECT
            count(*)::bigint AS cantidad_ventas,
            COALESCE(sum(total), 0)::numeric AS ingresos,
            COALESCE(sum(monto_pagado), 0)::numeric AS cobrado,
            COALESCE(sum(saldo_pendiente), 0)::numeric AS pendiente
        FROM ventas_filtradas
    ),
    ganancias AS (
        SELECT COALESCE(sum(
            (dv.precio_unitario * dv.cantidad)
            - (dv.precio_costo * dv.cantidad)
            - COALESCE(dv.descuento, 0)
            + COALESCE(dv.impuesto, 0)
        ), 0)::numeric AS ganancia
        FROM public.detalle_ventas dv
        JOIN ventas_filtradas v ON v.id = dv.venta_id
    ),
    por_cliente AS (
        SELECT
            COALESCE(NULLIF(trim(v.cliente), ''), 'Sin cliente') AS cliente,
            count(*)::bigint AS ventas,
            COALESCE(sum(v.total), 0)::numeric AS ingresos,
            COALESCE(sum(dv.ganancia), 0)::numeric AS ganancia
        FROM ventas_filtradas v
        LEFT JOIN (
            SELECT venta_id, sum(
                (precio_unitario * cantidad)
                - (precio_costo * cantidad)
                - COALESCE(descuento, 0)
                + COALESCE(impuesto, 0)
            ) AS ganancia
            FROM public.detalle_ventas
            GROUP BY venta_id
        ) dv ON dv.venta_id = v.id
        GROUP BY COALESCE(NULLIF(trim(v.cliente), ''), 'Sin cliente')
        ORDER BY ingresos DESC
    )
    SELECT jsonb_build_object(
        'desde', p_desde,
        'hasta', p_hasta,
        'resumen', (SELECT jsonb_build_object(
            'cantidad_ventas', r.cantidad_ventas,
            'ingresos', r.ingresos,
            'cobrado', r.cobrado,
            'pendiente', r.pendiente,
            'ganancia', g.ganancia
        ) FROM resumen r CROSS JOIN ganancias g),
        'clientes', COALESCE((SELECT jsonb_agg(to_jsonb(c)) FROM por_cliente c), '[]'::jsonb)
    ) INTO resultado;

    RETURN resultado;
END;
$function$;

