CREATE OR REPLACE FUNCTION public.admin_registrar_pago(
    p_empresa_id uuid,
    p_monto numeric,
    p_moneda text,
    p_metodo text,
    p_fecha_pago date,
    p_comprobante_url text DEFAULT NULL,
    p_nota text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
    pago_id bigint;
BEGIN
    IF NOT public.admin_es_desarrollador() THEN
        RAISE EXCEPTION 'Acceso reservado al desarrollador';
    END IF;

    IF p_monto IS NULL OR p_monto < 0 THEN
        RAISE EXCEPTION 'El monto del pago no es válido';
    END IF;

    INSERT INTO public.admin_pagos (empresa_id, monto, moneda, metodo, fecha_pago, comprobante_url, nota, registrado_por)
