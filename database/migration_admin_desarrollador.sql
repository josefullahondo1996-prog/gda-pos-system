-- Acceso seguro al panel privado del desarrollador.
-- Registrar el auth_user_id del desarrollador en developer_admins antes de usar el panel.

CREATE TABLE IF NOT EXISTS public.developer_admins (
    auth_user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    nombre text,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.developer_admins ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.admin_auditoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_auth_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
    accion text NOT NULL,
    empresa_id uuid REFERENCES public.empresas(id) ON DELETE SET NULL,
    usuario_id bigint REFERENCES public.usuarios(id) ON DELETE SET NULL,
    detalle jsonb NOT NULL DEFAULT '{}'::jsonb,
    creado_en timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.admin_auditoria ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.admin_suscripciones (
    empresa_id uuid PRIMARY KEY REFERENCES public.empresas(id) ON DELETE CASCADE,
    plan text NOT NULL DEFAULT 'prueba',
    estado text NOT NULL DEFAULT 'prueba',
    fecha_inicio timestamptz NOT NULL DEFAULT now(),
    fecha_vencimiento timestamptz,
    limite_usuarios integer NOT NULL DEFAULT 5,
    limite_productos integer NOT NULL DEFAULT 500,
    actualizado_en timestamptz NOT NULL DEFAULT now(),
    CHECK (plan IN ('prueba', 'basico', 'profesional', 'empresarial')),
    CHECK (estado IN ('prueba', 'activa', 'vencida', 'cancelada'))
);

ALTER TABLE public.admin_suscripciones ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.admin_pagos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
    monto numeric(14,2) NOT NULL CHECK (monto >= 0),
    moneda text NOT NULL DEFAULT 'PYG',
    metodo text NOT NULL DEFAULT 'transferencia',
    estado text NOT NULL DEFAULT 'pendiente',
    fecha_pago date NOT NULL DEFAULT current_date,
    comprobante_url text,
    nota text,
    registrado_por uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
    creado_en timestamptz NOT NULL DEFAULT now(),
    CHECK (metodo IN ('transferencia', 'efectivo', 'tarjeta', 'otro')),
    CHECK (estado IN ('pendiente', 'aprobado', 'rechazado'))
);

ALTER TABLE public.admin_pagos ENABLE ROW LEVEL SECURITY;

INSERT INTO public.admin_suscripciones (empresa_id, fecha_vencimiento)
SELECT id, now() + interval '30 days'
FROM public.empresas
ON CONFLICT (empresa_id) DO NOTHING;

ALTER TABLE public.empresas
    ADD COLUMN IF NOT EXISTS estado text NOT NULL DEFAULT 'activa';

UPDATE public.empresas
SET estado = 'activa'
WHERE estado IS NULL OR estado NOT IN ('activa', 'suspendida');

CREATE OR REPLACE FUNCTION public.admin_es_desarrollador()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
    SELECT EXISTS (
        SELECT 1
        FROM public.developer_admins
        WHERE auth_user_id = auth.uid()
          AND activo = true
    );
$function$;

CREATE OR REPLACE FUNCTION public.consultar_limites_empresa(p_empresa_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
    suscripcion public.admin_suscripciones%ROWTYPE;
    resultado jsonb;
BEGIN
    IF mi_empresa_id() IS DISTINCT FROM p_empresa_id THEN
        RAISE EXCEPTION 'Empresa no autorizada';
    END IF;

    SELECT * INTO suscripcion
    FROM public.admin_suscripciones
    WHERE empresa_id = p_empresa_id;

    IF NOT FOUND THEN
        RETURN jsonb_build_object('usuarios', 0, 'productos', 0, 'limite_usuarios', 5, 'limite_productos', 500);
    END IF;

    SELECT jsonb_build_object(
        'usuarios', (SELECT count(*) FROM public.usuarios WHERE empresa_id = p_empresa_id),
        'productos', (SELECT count(*) FROM public.productos WHERE empresa_id = p_empresa_id),
        'limite_usuarios', suscripcion.limite_usuarios,
        'limite_productos', suscripcion.limite_productos,
        'plan', suscripcion.plan,
        'estado', suscripcion.estado
    ) INTO resultado;
    RETURN resultado;
END;
$function$;

