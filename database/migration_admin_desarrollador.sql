CREATE OR REPLACE FUNCTION public.admin_listar_suscripciones()
RETURNS TABLE (
    empresa_id uuid,
    empresa text,
    plan text,
    estado text,
    fecha_vencimiento timestamptz,
    usuarios bigint,
    productos bigint,
    limite_usuarios integer,
    limite_productos integer
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
    IF NOT public.admin_es_desarrollador() THEN
        RAISE EXCEPTION 'Acceso reservado al desarrollador';
    END IF;

    RETURN QUERY
    SELECT s.empresa_id, e.nombre,
           s.plan,
           CASE
               WHEN s.fecha_vencimiento IS NOT NULL
                AND s.fecha_vencimiento < now()
                AND s.estado IN ('prueba', 'activa') THEN 'vencida'
               ELSE s.estado
           END AS estado,
           s.fecha_vencimiento,
           (SELECT count(*)::bigint FROM public.usuarios u WHERE u.empresa_id = e.id),
           (SELECT count(*)::bigint FROM public.productos p WHERE p.empresa_id = e.id),
           s.limite_usuarios, s.limite_productos
    FROM public.admin_suscripciones s
    JOIN public.empresas e ON e.id = s.empresa_id
    ORDER BY s.fecha_vencimiento NULLS LAST, e.nombre;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_actualizar_suscripcion(
    p_empresa_id uuid,
    p_plan text,
    p_estado text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
    IF NOT public.admin_es_desarrollador() THEN
        RAISE EXCEPTION 'Acceso reservado al desarrollador';
    END IF;

    IF p_plan NOT IN ('prueba', 'basico', 'profesional', 'empresarial')
       OR p_estado NOT IN ('prueba', 'activa', 'vencida', 'cancelada') THEN
        RAISE EXCEPTION 'Plan o estado de suscripción no válido';
    END IF;

    UPDATE public.admin_suscripciones
    SET plan = p_plan,
        estado = p_estado,
        limite_usuarios = CASE p_plan
            WHEN 'prueba' THEN 5
            WHEN 'basico' THEN 10
            WHEN 'profesional' THEN 25
            WHEN 'empresarial' THEN 100
        END,
        limite_productos = CASE p_plan
            WHEN 'prueba' THEN 500
            WHEN 'basico' THEN 2000
            WHEN 'profesional' THEN 10000
            WHEN 'empresarial' THEN 50000
        END,
        actualizado_en = now()
    WHERE empresa_id = p_empresa_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Suscripción no encontrada';
    END IF;

    PERFORM public.admin_registrar_auditoria('actualizar_suscripcion', p_empresa_id, NULL, jsonb_build_object('plan', p_plan, 'estado', p_estado));
END;
$function$;

