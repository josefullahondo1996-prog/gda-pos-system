CREATE OR REPLACE FUNCTION public.admin_listar_empresas()
RETURNS TABLE (
    id uuid,
    nombre text,
    email text,
    telefono text,
    creado_en timestamptz,
    estado text,
    usuarios bigint
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
    IF NOT public.admin_es_desarrollador() THEN
        RAISE EXCEPTION 'Acceso reservado al desarrollador';
    END IF;

    RETURN QUERY
    SELECT
        e.id,
        e.nombre,
        COALESCE(min(u.email), '')::text AS email,
        COALESCE(min(u.telefono_movil), '')::text AS telefono,
        e.creado_en,
        e.estado,
        count(u.id)::bigint AS usuarios
    FROM public.empresas e
    LEFT JOIN public.usuarios u ON u.empresa_id = e.id
    GROUP BY e.id, e.nombre, e.creado_en, e.estado
    ORDER BY e.creado_en DESC;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_detalle_empresa(p_empresa_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
    resultado jsonb;
BEGIN
    IF NOT public.admin_es_desarrollador() THEN
        RAISE EXCEPTION 'Acceso reservado al desarrollador';
    END IF;

    SELECT jsonb_build_object(
        'empresa', jsonb_build_object(
            'id', e.id,
            'nombre', e.nombre,
            'direccion', e.direccion,
            'telefono', e.telefono,
            'creado_en', e.creado_en,
            'estado', e.estado
        ),
        'usuarios', COALESCE((
            SELECT jsonb_agg(jsonb_build_object(
                'id', u.id,
                'nombre', u.nombre,
                'apellido', u.apellido,
                'email', u.email,
                'activo', u.activo,
                'permitir_acceso', u.permitir_acceso
            ) ORDER BY u.nombre)
            FROM public.usuarios u
            WHERE u.empresa_id = e.id
        ), '[]'::jsonb)
    )
    INTO resultado
    FROM public.empresas e
    WHERE e.id = p_empresa_id;

    IF resultado IS NULL THEN
        RAISE EXCEPTION 'Empresa no encontrada';
    END IF;

    RETURN resultado;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_actualizar_empresa(
