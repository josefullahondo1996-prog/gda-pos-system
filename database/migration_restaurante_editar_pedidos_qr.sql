-- Permite corregir comandas QR de mesa antes del cobro, con motivo e historial.
-- Aplicar después de migration_restaurante_cuentas_qr.sql.

CREATE TABLE IF NOT EXISTS public.pedidos_qr_cambios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id uuid NOT NULL REFERENCES public.pedidos(id) ON DELETE CASCADE,
  empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  usuario_id uuid NOT NULL,
  motivo text NOT NULL,
  items_anteriores jsonb NOT NULL,
  total_anterior numeric(14,2) NOT NULL,
  nota_anterior text,
  items_nuevos jsonb NOT NULL,
  total_nuevo numeric(14,2) NOT NULL,
  nota_nueva text,
  creado_en timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.pedidos_qr_cambios ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS pedidos_qr_cambios_select_empresa ON public.pedidos_qr_cambios;
CREATE POLICY pedidos_qr_cambios_select_empresa ON public.pedidos_qr_cambios
  FOR SELECT TO authenticated USING (EXISTS (
    SELECT 1 FROM public.usuarios u WHERE u.auth_user_id=auth.uid()
      AND u.empresa_id=pedidos_qr_cambios.empresa_id AND u.activo IS TRUE AND u.permitir_acceso IS TRUE
  ));
GRANT SELECT ON public.pedidos_qr_cambios TO authenticated;

CREATE OR REPLACE FUNCTION public.corregir_pedido_qr_mesa(
  p_pedido_id uuid, p_items jsonb, p_nota text, p_motivo text
) RETURNS numeric
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  v_pedido public.pedidos%rowtype;
  v_mesa public.catalogos_qr_mesas%rowtype;
  v_catalogo public.catalogos_qr%rowtype;
  v_item jsonb;
  v_producto public.productos%rowtype;
  v_producto_key text;
  v_cantidad numeric;
  v_stock numeric;
  v_precio numeric;
  v_subtotal numeric;
  v_total numeric := 0;
  v_items jsonb := '[]'::jsonb;
  v_ids text[] := '{}';
BEGIN
  IF auth.uid() IS NULL OR p_pedido_id IS NULL OR p_items IS NULL
     OR jsonb_typeof(p_items) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_items) < 1 OR jsonb_array_length(p_items) > 50
     OR length(btrim(coalesce(p_motivo,''))) < 3 OR length(p_motivo) > 500
     OR length(coalesce(p_nota,'')) > 500 THEN
    RAISE EXCEPTION 'PEDIDO_QR_CORRECCION_INVALIDA';
  END IF;
  SELECT * INTO v_pedido FROM public.pedidos WHERE id=p_pedido_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'PEDIDO_QR_NO_ENCONTRADO'; END IF;
  IF v_pedido.origen <> 'catalogo_qr_mesa' OR v_pedido.mesa_id IS NULL
     OR v_pedido.estado NOT IN ('pendiente','en_preparacion','completado')
     OR EXISTS (SELECT 1 FROM public.pedidos_qr_ventas pv WHERE pv.pedido_id=v_pedido.id) THEN
    RAISE EXCEPTION 'PEDIDO_QR_NO_CORREGIBLE';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.usuarios u WHERE u.auth_user_id=auth.uid()
      AND u.empresa_id=v_pedido.empresa_id AND u.activo IS TRUE AND u.permitir_acceso IS TRUE) THEN
    RAISE EXCEPTION 'USUARIO_SIN_ACCESO_A_PEDIDO_QR';
  END IF;
  SELECT * INTO v_mesa FROM public.catalogos_qr_mesas WHERE id=v_pedido.mesa_id;
  SELECT * INTO v_catalogo FROM public.catalogos_qr
    WHERE id=v_mesa.catalogo_id AND empresa_id=v_pedido.empresa_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'CATALOGO_QR_NO_DISPONIBLE'; END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    BEGIN
      v_producto_key := btrim(coalesce(v_item->>'producto_id',''));
      v_cantidad := (v_item->>'cantidad')::numeric;
    EXCEPTION WHEN invalid_text_representation THEN RAISE EXCEPTION 'ITEM_INVALIDO';
    END;
    IF v_producto_key = '' OR v_cantidad IS NULL OR v_cantidad <= 0
       OR v_cantidad::text IN ('NaN','Infinity','-Infinity') OR v_producto_key=ANY(v_ids) THEN
      RAISE EXCEPTION 'ITEM_INVALIDO';
    END IF;
    v_ids := array_append(v_ids,v_producto_key);
    SELECT * INTO v_producto FROM public.productos p
      WHERE p.id::text=v_producto_key AND p.empresa_id=v_pedido.empresa_id
        AND coalesce(p.activo,true)=true
        AND (cardinality(v_catalogo.categoria)=0 OR p.categoria=ANY(v_catalogo.categoria))
        AND (cardinality(v_catalogo.marca)=0 OR p.marca=ANY(v_catalogo.marca))
        AND (v_catalogo.precio_min IS NULL OR coalesce(p.precio_venta,0)>=v_catalogo.precio_min)
        AND (v_catalogo.precio_max IS NULL OR coalesce(p.precio_venta,0)<=v_catalogo.precio_max);
    IF NOT FOUND THEN RAISE EXCEPTION 'PRODUCTO_NO_DISPONIBLE'; END IF;
    IF v_pedido.ubicacion_id IS NULL THEN
      v_stock := greatest(coalesce(v_producto.stock_actual,0),0);
    ELSE
      SELECT ps.cantidad INTO v_stock FROM public.producto_stock_ubicacion ps
        WHERE ps.producto_id=v_producto.id AND ps.empresa_id=v_pedido.empresa_id
          AND ps.ubicacion_id=v_pedido.ubicacion_id;
      IF NOT FOUND OR coalesce(v_stock,0)<=0 THEN v_stock:=greatest(coalesce(v_producto.stock_actual,0),0);
      ELSE v_stock:=greatest(v_stock,0); END IF;
    END IF;
    IF v_stock < v_cantidad THEN RAISE EXCEPTION 'STOCK_INSUFICIENTE:%',v_producto.nombre; END IF;
    v_precio:=greatest(coalesce(v_producto.precio_venta,0),0);
    v_subtotal:=round(v_precio*v_cantidad,2);
    v_total:=v_total+v_subtotal;
    v_items:=v_items||jsonb_build_array(jsonb_build_object(
      'producto_id',v_producto.id,'nombre',v_producto.nombre,'codigo',coalesce(v_producto.codigo,''),
      'cantidad',v_cantidad,'precio_unitario',v_precio,'subtotal',v_subtotal,
      'unidad',coalesce(to_jsonb(v_producto)->>'unidad','')
    ));
  END LOOP;

  INSERT INTO public.pedidos_qr_cambios (pedido_id,empresa_id,usuario_id,motivo,
    items_anteriores,total_anterior,nota_anterior,items_nuevos,total_nuevo,nota_nueva)
  VALUES (v_pedido.id,v_pedido.empresa_id,auth.uid(),btrim(p_motivo),v_pedido.items,
    v_pedido.total,v_pedido.nota,v_items,v_total,nullif(btrim(coalesce(p_nota,'')),''));
  UPDATE public.pedidos SET items=v_items,total=v_total,
    nota=nullif(btrim(coalesce(p_nota,'')),''),actualizado_en=now()
  WHERE id=v_pedido.id;
  RETURN v_total;
END;
$$;
REVOKE ALL ON FUNCTION public.corregir_pedido_qr_mesa(uuid,jsonb,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.corregir_pedido_qr_mesa(uuid,jsonb,text,text) TO authenticated;

