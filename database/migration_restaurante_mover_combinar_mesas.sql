-- Historial de movimientos y fusion de cuentas QR entre mesas del mismo catalogo.
-- Aplicar despues de migration_restaurante_cuentas_qr.sql y migration_restaurante_editar_pedidos_qr.sql.

CREATE TABLE IF NOT EXISTS public.pedidos_qr_movimientos_mesa (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  mesa_origen_id uuid NOT NULL,
  mesa_origen_nombre text NOT NULL,
  mesa_destino_id uuid NOT NULL,
  mesa_destino_nombre text NOT NULL,
  pedido_ids uuid[] NOT NULL,
  cantidad_pedidos integer NOT NULL CHECK (cantidad_pedidos > 0),
  usuario_id uuid NOT NULL,
  motivo text NOT NULL,
  creado_en timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.pedidos_qr_movimientos_mesa ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS pedidos_qr_movimientos_select_empresa ON public.pedidos_qr_movimientos_mesa;
CREATE POLICY pedidos_qr_movimientos_select_empresa ON public.pedidos_qr_movimientos_mesa
  FOR SELECT TO authenticated USING (EXISTS (
    SELECT 1 FROM public.usuarios u WHERE u.auth_user_id=auth.uid()
      AND u.empresa_id=pedidos_qr_movimientos_mesa.empresa_id
      AND u.activo IS TRUE AND u.permitir_acceso IS TRUE
  ));
GRANT SELECT ON public.pedidos_qr_movimientos_mesa TO authenticated;

CREATE OR REPLACE FUNCTION public.mover_combinar_pedidos_qr_mesas(
  p_mesa_origen_id uuid, p_mesa_destino_id uuid, p_motivo text
) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  v_origen public.catalogos_qr_mesas%rowtype;
  v_destino public.catalogos_qr_mesas%rowtype;
  v_ids uuid[];
  v_cantidad integer;
BEGIN
  IF auth.uid() IS NULL OR p_mesa_origen_id IS NULL OR p_mesa_destino_id IS NULL
    OR p_mesa_origen_id=p_mesa_destino_id
    OR length(btrim(coalesce(p_motivo,'')))<3 OR length(p_motivo)>500 THEN
    RAISE EXCEPTION 'MOVIMIENTO_MESA_INVALIDO';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.usuarios u
    WHERE u.auth_user_id=auth.uid() AND u.activo IS TRUE AND u.permitir_acceso IS TRUE) THEN
    RAISE EXCEPTION 'USUARIO_SIN_ACCESO_A_MESAS';
  END IF;

  -- Mantiene el mismo orden de bloqueos que el cobro: pedidos y luego mesas.
  PERFORM 1 FROM public.pedidos p
    WHERE p.mesa_id=p_mesa_origen_id AND p.origen='catalogo_qr_mesa'
      AND p.estado IN ('pendiente','en_preparacion','completado')
      AND NOT EXISTS (SELECT 1 FROM public.pedidos_qr_ventas pv WHERE pv.pedido_id=p.id)
    ORDER BY p.id FOR UPDATE;
  PERFORM 1 FROM public.catalogos_qr_mesas m
    WHERE m.id IN (p_mesa_origen_id,p_mesa_destino_id) ORDER BY m.id FOR UPDATE;
  SELECT * INTO v_origen FROM public.catalogos_qr_mesas WHERE id=p_mesa_origen_id;
  SELECT * INTO v_destino FROM public.catalogos_qr_mesas WHERE id=p_mesa_destino_id;
  IF NOT FOUND OR v_origen.id IS NULL OR v_destino.id IS NULL THEN
    RAISE EXCEPTION 'MESA_NO_ENCONTRADA';
  END IF;
  IF v_origen.empresa_id IS DISTINCT FROM v_destino.empresa_id
    OR v_origen.catalogo_id IS DISTINCT FROM v_destino.catalogo_id
    OR NOT v_origen.activo OR NOT v_destino.activo THEN
    RAISE EXCEPTION 'MESAS_NO_COMPATIBLES';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.usuarios u WHERE u.auth_user_id=auth.uid()
    AND u.empresa_id=v_origen.empresa_id AND u.activo IS TRUE AND u.permitir_acceso IS TRUE) THEN
    RAISE EXCEPTION 'USUARIO_SIN_ACCESO_A_MESAS';
  END IF;

  -- Relee y vuelve a bloquear despues de serializar ambos QR; incluye un posible ultimo pedido concurrente.
  PERFORM 1 FROM public.pedidos p
    WHERE p.mesa_id=p_mesa_origen_id AND p.origen='catalogo_qr_mesa'
      AND p.estado IN ('pendiente','en_preparacion','completado')
      AND NOT EXISTS (SELECT 1 FROM public.pedidos_qr_ventas pv WHERE pv.pedido_id=p.id)
    ORDER BY p.id FOR UPDATE;
  SELECT array_agg(p.id ORDER BY p.id), count(*)::integer INTO v_ids,v_cantidad
    FROM public.pedidos p
    WHERE p.mesa_id=p_mesa_origen_id AND p.empresa_id=v_origen.empresa_id
      AND p.origen='catalogo_qr_mesa' AND p.estado IN ('pendiente','en_preparacion','completado')
      AND NOT EXISTS (SELECT 1 FROM public.pedidos_qr_ventas pv WHERE pv.pedido_id=p.id);
  IF coalesce(v_cantidad,0)=0 THEN RAISE EXCEPTION 'MESA_ORIGEN_SIN_PEDIDOS_ABIERTOS'; END IF;

  UPDATE public.pedidos SET mesa_id=v_destino.id, mesa_nombre=v_destino.nombre, actualizado_en=now()
    WHERE id=ANY(v_ids) AND empresa_id=v_origen.empresa_id;
  INSERT INTO public.pedidos_qr_movimientos_mesa (
    empresa_id,mesa_origen_id,mesa_origen_nombre,mesa_destino_id,mesa_destino_nombre,
    pedido_ids,cantidad_pedidos,usuario_id,motivo
  ) VALUES (
    v_origen.empresa_id,v_origen.id,v_origen.nombre,v_destino.id,v_destino.nombre,
    v_ids,v_cantidad,auth.uid(),btrim(p_motivo)
  );
  RETURN v_cantidad;
END;
$$;
REVOKE ALL ON FUNCTION public.mover_combinar_pedidos_qr_mesas(uuid,uuid,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.mover_combinar_pedidos_qr_mesas(uuid,uuid,text) TO authenticated;
